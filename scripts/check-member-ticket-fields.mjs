import assert from 'node:assert/strict';
import WebSocket from 'ws';
const targets = await (await fetch(`http://127.0.0.1:${Number(process.env.SERENE_BROWSER_PORT ?? 9224)}/json`, { signal: AbortSignal.timeout(10000) })).json();
const socket = new WebSocket(targets.find(target => target.type === 'page').webSocketDebuggerUrl);
await new Promise((resolve, reject) => { socket.once('open', resolve); socket.once('error', reject); });
let id = 0;
const pending = new Map();
socket.on('message', raw => { const message = JSON.parse(raw); if (!message.id) return; const call = pending.get(message.id); pending.delete(message.id); if (message.error) call.reject(message.error); else call.resolve(message.result); });
const send = (method, params = {}) => new Promise((resolve, reject) => { const next = ++id; pending.set(next, { resolve, reject }); socket.send(JSON.stringify({ id: next, method, params })); });
const evaluate = async expression => { const result = await send('Runtime.evaluate', { expression, returnByValue: true }); if (result.exceptionDetails) throw new Error(JSON.stringify(result.exceptionDetails)); return result.result.value; };
const pause = () => new Promise(resolve => setTimeout(resolve, 80));
const until = async expression => { for (let i = 0; i < 50; i++) { if (await evaluate(expression)) return; await pause(); } throw new Error(`Timed out: ${expression}`); };
const button = text => `Array.from(document.querySelectorAll('button')).find(el => el.textContent.trim() === ${JSON.stringify(text)})`;
const control = label => `Array.from(document.querySelectorAll('label')).find(el => el.querySelector('span')?.textContent.trim() === ${JSON.stringify(label)})?.querySelector('button,input,textarea')`;
const click = async expression => { assert.ok(await evaluate(`!!(${expression})`), `Control exists: ${expression}`); await evaluate(`(${expression}).click()`); await pause(); };
const choose = async (expression, label) => { await click(expression); await until('!!document.querySelector("[role=option]")'); await click(`Array.from(document.querySelectorAll('[role=option]')).find(el => el.textContent.trim() === ${JSON.stringify(label)})`); await pause(); };
const fill = async (expression, value) => { await evaluate(`(() => { const el = ${expression}; Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(value)}); el.dispatchEvent(new Event('input',{bubbles:true})); })()`); await pause(); };
const open = async form => { await send('Page.navigate', { url: new URL(`../output/member-ticket-fields.html?form=${form}`, import.meta.url).href }); await until('!!document.querySelector("#categories")'); };
try {
  await open('member');
  await fill(control('Name *'), 'Test Member');
  await choose(control('Queendom'), 'Mumbai');
  await click(control('Tier'));
  const tier = await evaluate(`Array.from(document.querySelectorAll('[role=option]')).find(el => el.textContent.trim() !== 'Not set').textContent.trim()`);
  await click(button(tier));
  await click(button('Add member'));
  await until('window.fieldReview.calls.length === 1');
  const member = await evaluate('window.fieldReview.calls[0].payload');
  assert.equal(member.full_name, 'Test Member');
  assert.equal(member.queendom_id, 'q-1');
  assert.ok(member.tier);
  assert.equal(await evaluate(`${control('Name *')}.value`), 'Test Member', 'rejected save retains draft');
  assert.equal(await evaluate(`${control('Queendom')}.textContent.trim()`), 'Mumbai');
  console.log('Member: themed choices reach the save payload and survive rejection.');

  await open('ticket');
  await until('!!document.querySelector("label")');
  const data = await evaluate('JSON.parse(document.querySelector("#categories").textContent)');
  const category = data.categories.find(item => data.subs[item.id]?.length);
  await choose(control('Category'), category.label);
  const sub = data.subs[category.id][0];
  await choose(control('Sub-category'), sub.label);
  const other = data.categories.find(item => item.id !== category.id);
  await choose(control('Category'), other.label);
  await choose(control('Category'), category.label);
  assert.equal(await evaluate(`${control('Sub-category')}.textContent.trim()`), 'Not set', 'category change resets dependent sub-category');
  await choose(control('Sub-category'), sub.label);
  await choose(control('Genie'), 'Ada (genie)');
  await fill(control('Title'), 'Test ticket');
  await click(button('Create ticket'));
  await until('window.fieldReview.calls.length === 1');
  const ticket = await evaluate('window.fieldReview.calls[0].payload');
  assert.equal(ticket.category, category.id);
  assert.equal(ticket.sub_category, sub.id);
  assert.equal(ticket.assignee_id, 'genie-1');
  assert.equal(ticket.member_id, 'member-1');
  assert.equal(ticket.title, 'Test ticket');
  console.log('Ticket: category dependencies, assignee, and creation payload passed.');

  await open('policy');
  await click(button('New policy'));
  await choose(`document.querySelector('button[aria-label^="Queendom:"]')`, 'Mumbai');
  await choose(`document.querySelector('button[aria-label^="Category:"]')`, category.label);
  await choose(`document.querySelector('button[aria-label^="Sub-category:"]')`, sub.label);
  await choose(`document.querySelector('button[aria-label^="Escalation recipient:"]')`, 'the founder');
  await click(button('Add policy'));
  await until('window.fieldReview.calls.length === 1');
  const policy = await evaluate('window.fieldReview.calls[0].payload');
  assert.equal(policy.queendom_id, 'q-1');
  assert.equal(policy.category, category.id);
  assert.equal(policy.sub_category, sub.id);
  assert.equal(policy.escalation[0].to, 'founder');
  assert.equal(policy.first_response_min, 15);
  console.log('SLA settings: scope, escalation recipient, and existing clock values passed.');
} finally { socket.close(); }
